// This patch is here to make JSON.stringify support bigint fields, which it doesn't natively... https://playcode.io/1995253
// We need to import it manually everytime an API endpoint may contain a bigint in its response which is really inconvenient...
// but there doesn't seem to be a single place that could work for an API project like this...
// FIXME Possible alternative it to not use this simple patch, but use some kind of helper function to convert bigint to string in all payloads...
(BigInt as any).prototype.toJSON = function () {
  return this.toString();
};
